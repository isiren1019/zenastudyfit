// ── 유효한 모든 슬러그 세트 + 빠른 파싱 맵 생성 ────────────────
// AREAS × GRADES × SUBJECTS 조합으로 모든 가능한 슬러그를 미리 생성
// (런타임 라우팅 시 O(1) 조회 가능)
function buildSlugSet() {
  const set = new Set();
  const map = new Map();
  for (const [city, gu, dong] of AREAS) {
    for (const grade of GRADES) {
      for (const subject of SUBJECTS) {
        const slug = `${city}-${gu}-${dong}-${grade}-${subject}-과외`.replace(/ /g, "-");
        set.add(slug);
        map.set(slug, { city, gu, dong, grade, subject });
      }
    }
  }
  return { set, map };
}

const _built = buildSlugSet();
export const VALID_SLUGS = _built.set;
export const SLUG_MAP = _built.map;

// ── 슬러그 파싱 헬퍼 ─────────────────────────────────────────
// 예: "서울특별시-강남구-대치동-고등-수학-과외" → {city, gu, dong, grade, subject}
//     찾지 못하면 null 반환
export function parseSlug(slug) {
  return SLUG_MAP.get(slug) || null;
}
