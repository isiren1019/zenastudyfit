export function makeIntro(rng, city, gu, dong, grade, subject) {
  const reg = regionVars(city, gu, dong);
  const title = fmt(pickS(rng, INTRO_TITLES), {city,gu,dong,grade,subject,...reg});
  const body = fmt(pickS(rng, INTRO_BODIES), {
    city,gu,dong,grade,subject,...reg,
    trait_grade: pickS(rng, GRADE_TRAITS[grade]),
    trait_subject: pickS(rng, SUBJECT_TRAITS[subject] || SUBJECT_TRAITS["국어"]),
  });
  return [title, body];
}

export function makeBody(rng, city, gu, dong, grade, subject) {
  const reg = regionVars(city, gu, dong);
  const title = fmt(pickS(rng, BODY_TITLES), {city,gu,dong,grade,subject,...reg});
  const body = fmt(pickS(rng, BODY_BODIES[grade]), {
    city,gu,dong,grade,subject,...reg,
    trait_subject: pickS(rng, SUBJECT_TRAITS[subject] || SUBJECT_TRAITS["국어"]),
  });
  return [title, body];
}

export function makeConclusion(rng, city, gu, dong, grade, subject) {
  const reg = regionVars(city, gu, dong);
  const title = fmt(pickS(rng, CONCLUSION_TITLES), {city,gu,dong,grade,subject,...reg});
  const body = fmt(pickS(rng, CONCLUSION_BODIES), {city,gu,dong,grade,subject,...reg});
  return [title, body];
}

export function makeFeatures(rng, subject, grade) {
  const pool = [...FEATURE_POOL];
  // seeded shuffle
  for (let i = pool.length-1; i>0; i--) {
    const j = Math.floor(rng() * (i+1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0,4).map(([icon,title,desc]) => [
    icon,
    fmt(title, {subject,grade}),
    fmt(desc, {subject,grade,grade_trait: GRADE_SHORT_TRAIT[grade]}),
  ]);
}

