export function makeSymptoms(rng, city, gu, dong, grade, subject, dispSubject) {
  const reg = regionVars(city, gu, dong);
  const set = (SYMPTOM_DATA[subject] && SYMPTOM_DATA[subject][grade]) || SYMPTOM_DATA["국어"]["중등"];
  const shown = dispSubject || subject;
  const vars = {city,gu,dong,grade,subject:shown,...reg};
  const title = fmt("이런 어려움이 있다면 {region_short} {grade} {subject} 과외가 필요합니다", vars);
  // 5개 중 시드로 4개 선택 (페이지별 조합 분산)
  const pool = [...set.items];
  for (let i = pool.length-1; i>0; i--) {
    const j = Math.floor(rng() * (i+1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  const items = pool.slice(0,4);
  const closing = fmt(pickS(rng, SYMPTOM_CLOSINGS), vars);
  return { title, lead: set.lead, items, closing };
}

